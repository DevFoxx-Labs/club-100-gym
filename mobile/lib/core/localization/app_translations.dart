/// Resolves [key] to the string in the admin's currently selected language,
/// falling back to English and then to the raw key if a translation is
/// missing. Supports simple `{placeholder}` substitution via [params].
String tr(String key, [Map<String, String>? params]) {
  final entry = AppTranslations.values[key];
  var text = entry != null
      ? (entry[LocaleService.instance.current.code] ?? entry['en'] ?? key)
      : key;
  if (params != null) {
    for (final e in params.entries) {
      text = text.replaceAll('{${e.key}}', e.value);
    }
  }
  return text;
}

